"""Deterministic synthetic ground-truth datasets.

Used until real datasets can be built from Twitch/Kick (needs the owner's API keys; see BUILD_LOG "Needs B").
Generators include realistic confounders (missing chat spans, loud music without chat, reaction lag, varied
baselines) so stages can't pass by construction. Real-data builders live in clipping/eval/real.py.
"""

from __future__ import annotations

import numpy as np

from clipping.eval import datasets

SYNTH_NOTE = "synthetic: generated by clipping.eval.synthetic; replace/augment with real data once Twitch keys exist"


def radar_creators(seed: int = 1, n: int = 90) -> None:
    rng = np.random.default_rng(seed)
    langs = ["en", "es", "pt"]
    creators = []
    for i in range(n):
        lang = langs[i % 3]
        base = float(np.exp(rng.normal(6.0, 1.3)))           # avg viewers
        growth = float(rng.normal(0.0, 0.25))
        clippy = float(np.exp(rng.normal(0, 0.5)))             # clips per viewer-hour factor
        hours_wk = float(np.clip(rng.normal(25, 12), 2, 70))
        platform = "twitch" if rng.random() < 0.75 else "kick"
        samples, clips = [], []
        for week, mult in ((1, 1.0), (0, 1.0 + growth)):        # week 1 = 168-336h ago, week 0 = last 7 days
            hrs = hours_wk * float(np.clip(rng.normal(1, 0.2), 0.3, 2))
            n_samp = int(hrs * 6)
            starts = sorted(rng.uniform(0, 168 - hrs / 6, size=max(1, int(hrs // 5) + 1)))
            for k in range(n_samp):
                t = week * 168 + float(starts[k % len(starts)]) + (k // len(starts)) / 6
                v = max(0, int(base * mult * float(np.exp(rng.normal(0, 0.25)))))
                samples.append([round(t, 3), True, v])
            if platform == "twitch":
                rate = clippy * (base * mult) ** 0.5 / 10
                for _ in range(rng.poisson(max(rate * hrs, 0.1))):
                    clips.append([round(week * 168 + float(rng.uniform(0, 168)), 2), int(np.exp(rng.normal(np.log(base * mult + 1) - 1, 1)))])
        off = float(base * np.exp(rng.normal(1, 0.8))) if rng.random() < 0.5 else None
        next_growth = growth * 0.6 + float(rng.normal(0, 0.1))
        next_hours = hours_wk * float(np.clip(rng.normal(1, 0.25), 0.2, 2))
        target = base * (1 + growth) * (1 + next_growth) * next_hours * float(np.exp(rng.normal(0, 0.3)))
        creators.append({"id": i + 1, "language": lang, "platform": platform, "samples": samples, "clips": clips,
                         "offplatform": off, "next_week_hours_watched": round(target, 1)})
    datasets.write("radar_creators", "v1", {"creators.json": creators},
                   {"source": SYNTH_NOTE, "seed": seed, "n": n, "label": "next_week_hours_watched"})


BUILDERS = {"radar_creators": radar_creators}


def build_all(names: list[str] | None = None) -> list[str]:
    done = []
    for name, fn in BUILDERS.items():
        if names and name not in names:
            continue
        fn()
        done.append(name)
    return done
